#!/usr/bin/env bash
# Print what a PR description needs: branch, commits, files grouped by area,
# and the diff against the base branch.
# Usage: pr-context.sh [base]   (default base: origin/master)
#        PR_CONTEXT_MAX_DIFF=<lines> limits diff output (default 1500)

set -euo pipefail

base="${1:-origin/master}"
max_diff="${PR_CONTEXT_MAX_DIFF:-1500}"

# Skip lock files and build output; they are noise in a description.
exclude=(
  ':(exclude)uv.lock'
  ':(exclude)frontend/package-lock.json'
  ':(exclude)staticfiles/**'
)

git fetch --quiet origin 2>/dev/null || echo "(could not fetch origin; using local refs)"

branch="$(git branch --show-current)"
merge_base="$(git merge-base "$base" HEAD)"

echo "## Branch"
echo "$branch -> ${base#origin/}"
ahead="$(git rev-list --count "$merge_base"..HEAD)"
behind="$(git rev-list --count HEAD.."$base")"
echo "$ahead commit(s) ahead, $behind behind"
if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "WARNING: uncommitted changes are not part of the PR:"
  git status --short
fi

echo
echo "## Commits"
git log --reverse --format='- %s%n%w(0,2,2)%b' "$merge_base"..HEAD | sed '/^  $/d'

echo
echo "## Files by area"
git diff --name-status "$merge_base"..HEAD | awk '
  BEGIN {
    n = split("Frontend,Backend,Migrations,Agent skills,Tooling / CI,Docs,Other,Build output", order, ",")
  }
  {
    path = $NF
    if      (path ~ /^staticfiles\//)                               area = "Build output"
    else if (path ~ /^frontend\//)                                  area = "Frontend"
    else if (path ~ /^src\/apps\/.*\/migrations\//)                 area = "Migrations"
    else if (path ~ /^(src|tests)\//)                               area = "Backend"
    else if (path ~ /^\.(claude|agents)\/|^\.github\/skills\/|^skills-lock\.json$/) area = "Agent skills"
    else if (path ~ /^(\.github|docker|scripts|bin)\/|^(Makefile|pyproject\.toml|uv\.lock|package\.json|Procfile|\.pre-commit-config\.yaml|\.editorconfig|\.gitignore|\.python-version|\.env\.example)$/) area = "Tooling / CI"
    else if (path ~ /\.md$/)                                        area = "Docs"
    else                                                            area = "Other"
    count[area]++
    # Skill folders and build output are summarized, not listed file by file.
    if (area == "Build output") next
    if (area == "Agent skills" && count[area] > 15) next
    files[area] = files[area] "  " $1 " " path "\n"
  }
  END {
    for (i = 1; i <= n; i++) {
      a = order[i]
      if (!(a in count)) continue
      printf "%s (%d files)\n%s", a, count[a], files[a]
      if (a == "Build output") print "  (regenerated by make build)"
      if (a == "Agent skills" && count[a] > 15) print "  ..."
    }
  }'

echo
echo "## Diff stat"
git diff --stat "$merge_base"..HEAD -- . "${exclude[@]}" | tail -n 25

echo
echo "## Diff (lock files and staticfiles omitted)"
diff_out="$(git diff "$merge_base"..HEAD -- . "${exclude[@]}")"
total="$(printf '%s\n' "$diff_out" | wc -l | tr -d ' ')"
printf '%s\n' "$diff_out" | head -n "$max_diff"
if [ "$total" -gt "$max_diff" ]; then
  echo
  echo "(diff truncated at $max_diff of $total lines; read the remaining files directly)"
fi
